#!/usr/bin/env python3

###
# Splits the ELF according to the config.yml and generates a config.json based on it
#
# Usage:
#   python3 tools/splat_to_config_json.py config/VERSION/config.yml build/VERSION
###

import argparse
from pathlib import Path
import json
import splat.scripts.split as split


def generate_config_json(config_yml: Path, build_folder: Path) -> str:
    split.main(
        [config_yml],
        modes="all",
        verbose=True,
    )

    linker_entries = split.linker_writer.entries

    for entry in linker_entries:
        for src_path in entry.src_paths:
            if src_path.is_file():
                src_path.touch()

    config_json = {
        "version": "1.7.0",
        "name": "main",
        "module_id": 0,  # TODO for rels
        "ldscript": (build_folder / "ldscript.ld").as_posix(),
        "entry": "__start",  # TODO
        "units": [],
        "extract": [],
        "modules": [],
        "links": [],
    }

    seen_objects = set()
    for entry in linker_entries:
        seg = entry.segment

        if seg.type[0] == "." or seg.type in ("bin", "pad"):
            continue

        if entry.object_path is None or not entry.src_paths:
            continue

        src_path = entry.src_paths[0]
        if "asm" in src_path.parts:
            name = Path(*src_path.parts[src_path.parts.index("asm") + 1 :]).as_posix()
        elif "src" in src_path.parts:
            name = Path(*src_path.parts[src_path.parts.index("src") + 1 :]).as_posix()
        else:
            name = src_path.name

        obj_path = (build_folder / "obj" / name).as_posix().removesuffix(
            ".s"
        ).removesuffix(".cpp").removesuffix(".c") + ".o"
        if obj_path in seen_objects:
            continue
        seen_objects.add(obj_path)

        unit_name = name.removesuffix(".s")
        config_json["units"].append(
            {
                "object": obj_path,
                "name": unit_name,
                "autogenerated": False,  # TODO
                "code_size": 0,  # these are not needed
                "data_size": 0,
            }
        )

    return json.dumps(config_json)


def main() -> None:
    parser = argparse.ArgumentParser(
        description="""Splits the configured binary and generates a config.json"""
    )
    parser.add_argument(
        "yml_file",
        help="""Config yml in""",
    )
    parser.add_argument(
        "build_folder",
        help="""Build folder out""",
    )
    args = parser.parse_args()

    output = generate_config_json(Path(args.yml_file), Path(args.build_folder))

    config_json_path = Path(args.build_folder) / "config.json"
    with open(config_json_path, "w", encoding="UTF-8") as f:
        f.write(output)

    dep_path = Path(args.build_folder) / "dep"
    with open(dep_path, "w", encoding="UTF-8") as f:
        f.write(f"{config_json_path.as_posix()}: {Path(args.yml_file).as_posix()}\n")


if __name__ == "__main__":
    main()
